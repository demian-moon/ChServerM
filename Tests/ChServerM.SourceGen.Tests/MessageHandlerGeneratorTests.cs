    [Fact]
    public void WithoutHostingReference_WarnsCHSM1007_ValidationStillRuns()
    {
        const string Source = """
            using System.Threading.Tasks;
            using ChServerM.Dispatch;

            namespace TestApp;

            public sealed class ChatMessage { }

            [MessageHandler(0)]
            public sealed class ZeroHandler : IMessageHandler<ChatMessage>
            {
                public ValueTask HandleAsync(MessageContext context, ChatMessage message) => default;
            }

            [MessageHandler(100)]
            public sealed class OkHandler : IMessageHandler<ChatMessage>
            {
                public ValueTask HandleAsync(MessageContext context, ChatMessage message) => default;
            }
            """;

        (GeneratorRunResult result, _) = Run(Source, referenceHosting: false);

        // 검증(센티넬 ID)은 Hosting 없이도 돌고, 생성만 건너뛴다.
        Assert.Contains(result.Diagnostics, d => d.Id == "CHSM1003");
        Assert.Contains(result.Diagnostics, d => d.Id == "CHSM1007");
        Assert.Empty(result.GeneratedSources);
    }

    // ── 드라이버 도우미 ──────────────────────────────────────────────

    private static (GeneratorRunResult Result, Compilation Output) Run(string source, bool referenceHosting = true)
    {
        List<MetadataReference> references = [];

        // 테스트 러너 런타임의 참조 어셈블리 — BCL 해석용 표준 트릭.
        // ⚠ TPA 에는 러너가 로드한 ChServerM.* dll 도 들어 있다. 걸러내지 않으면
        // "Hosting 미참조" 시나리오가 성립하지 않는다(실제로 그렇게 한 번 깨졌다).
        string platformAssemblies = (string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!;
        foreach (string path in platformAssemblies.Split(Path.PathSeparator))
        {
            if (path.Length > 0
                && !Path.GetFileName(path).StartsWith("ChServerM.", StringComparison.Ordinal))
            {
                references.Add(MetadataReference.CreateFromFile(path));
            }
        }

        references.Add(MetadataReference.CreateFromFile(typeof(ChServerM.Identity.MessageId).Assembly.Location));

        if (referenceHosting)
        {
            references.Add(MetadataReference.CreateFromFile(
                typeof(ChServerM.Hosting.Dispatch.MessageDispatcherBuilder).Assembly.Location));
        }

        CSharpCompilation compilation = CSharpCompilation.Create(
            "GeneratorTestAssembly",
            [CSharpSyntaxTree.ParseText(source)],
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        GeneratorDriver driver = CSharpGeneratorDriver
            .Create(new MessageHandlerGenerator())
            .RunGeneratorsAndUpdateCompilation(compilation, out Compilation output, out _);

        return (driver.GetRunResult().Results[0], output);
    }

    private static string Normalize(string text) =>
        text.Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd('\n');
}
