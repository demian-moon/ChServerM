using System;

namespace ChServerM.Security;

/// <summary>
/// 크로스 커넥션 토큰 재사용을 막는 1회용 등록부 (T-05, ADR-0017 결정 4).
/// </summary>
/// <remarks>
/// <para>
/// <b>존재 이유.</b> 커넥션 <b>안</b>의 와이어 리플레이는 TLS 레코드 계층이 차단하지만
/// (ADR-0017 결정 4 — 그래서 레거시 <c>pid</c> 를 승계하지 않았다), 캡처한 로그인 토큰을
/// <b>새 커넥션</b>에서 재사용하는 경로는 인증 계층의 몫이다. 이 계약이 그 몫이다 —
/// 토큰은 1회용이고, 같은 토큰의 두 번째 클레임은 거부된다.
/// </para>
/// <para>
/// <b>⚠ 호출 순서 규약 — 검증 먼저, 클레임은 마지막.</b>
/// 서명·만료 등 토큰 자체의 유효성 검증이 <b>전부 통과한 뒤에만</b> 부른다.
/// 반대로 하면 공격자가 유효하지 않은 쓰레기 토큰으로 유계 등록부를 포화시켜
/// 정상 로그인 전체를 막는다(로그인 DoS). 유효 토큰만 등록부에 들어오면
/// 포화를 만들 수단이 "유효 토큰 대량 확보"뿐이 되고, 그것은 토큰 발급자의 문제다.
/// </para>
/// <para>
/// <b>토큰의 만료는 앱이 검증한다.</b> 토큰 형식(만료 시각 포함)은 앱 소관이다 —
/// 이 계약은 만료를 해석하지 않는다. 구현의 TTL 은 만료 검증의 대체가 아니라
/// <b>등록부 메모리를 유계로 만드는 장치</b>이며, 토큰 수명 이상으로 설정해야 한다
/// (짧으면 TTL 축출 후 아직 유효한 토큰이 재사용 가능해진다).
/// </para>
/// <para>
/// <b>스레드 규약.</b> 서로 다른 커넥션의 인증이 동시에 부른다 — 구현은 스레드 안전해야
/// 하며, 같은 토큰의 동시 클레임 경쟁에서 <b>정확히 하나만</b> <see langword="true"/> 를
/// 받아야 한다.
/// </para>
/// <para>
/// <b>범위.</b> 인메모리 구현은 단일 노드 한정이다 — 스케일아웃(노드 간 재사용)은
/// 외부 저장소 어댑터(Phase 13+)가 이 계약 뒤에 끼워진다.
/// </para>
/// </remarks>
public interface ITokenReplayGuard
{
    /// <summary>토큰의 첫 사용을 등록한다.</summary>
    /// <param name="token">검증을 통과한 토큰의 원시 바이트.</param>
    /// <returns>
    /// 첫 사용이면 <see langword="true"/>. 재사용이거나 등록부가 포화면
    /// <see langword="false"/> — <b>거부가 붕괴보다 낫다</b>(CLAUDE.md 9.6). 포화 거부는
    /// 로그로 구분해 관측한다(조용한 거부 금지).
    /// </returns>
    bool TryClaim(ReadOnlySpan<byte> token);
}
