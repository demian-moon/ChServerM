namespace ChServerM.Resilience;

/// <summary>
/// 현재 부하 수준을 알려주는 축 — 우아한 열화의 입력 (Phase 10).
/// </summary>
/// <remarks>
/// <para>
/// <b>존재 이유.</b> "부하 시 비필수 기능을 차단한다"는 정책은 <b>"지금 부하인가"를 답하는
/// 누군가</b>가 있어야 성립한다. 그 답의 출처는 조립마다 다르다 — 메모리 압박, 큐 깊이,
/// 지연 시간, 외부 오케스트레이터의 신호. 그래서 계약으로 분리한다.
/// </para>
/// <para>
/// <b>⚠ 핫패스에서 프레임마다 호출된다.</b> 열화 판정은 메시지 단위이므로 이 속성은
/// <b>싸야 한다</b> — 이미 계산된 값을 읽는 수준이어야 하고, 측정 자체가 비싸면(GC 정보 조회·
/// 시스템 호출) <b>구현이 캐시해서</b> 주기적으로만 갱신해야 한다. 이 계약은 "지금 값을
/// 계산하라"가 아니라 "지금 값을 알려달라"다.
/// </para>
/// <para>
/// <b>실패는 값이 아니라 낙관이다.</b> 부하를 측정할 수 없으면 <see cref="LoadLevel.Normal"/>
/// 을 돌려준다 — 측정 실패 때문에 정상 트래픽을 버리는 것이 더 나쁘다. 예외를 던지지 않는다.
/// </para>
/// <para><b>스레드 규약.</b> 모든 커넥션이 동시에 읽는다 — 구현은 스레드 안전해야 한다.</para>
/// </remarks>
public interface ILoadLevelSource
{
    /// <summary>현재 부하 수준.</summary>
    /// <remarks>프레임마다 읽히므로 싸야 한다(타입 문서의 핫패스 규약).</remarks>
    LoadLevel Current { get; }
}
