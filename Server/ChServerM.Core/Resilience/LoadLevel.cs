namespace ChServerM.Resilience;

/// <summary>
/// 서버가 지금 얼마나 압박받고 있는지 (Phase 10 우아한 열화).
/// </summary>
/// <remarks>
/// <para>
/// <b>값이 클수록 나쁘다.</b> 열화 정책은 "이 메시지는 <see cref="Normal"/> 까지만 처리한다"
/// 처럼 <b>유지 상한</b>으로 표현되며, 현재 레벨이 그 상한을 넘으면 그 메시지를 버린다.
/// 순서가 곧 비교 연산의 근거이므로 값 사이에 새 단계를 끼워 넣지 않는다.
/// </para>
/// <para>
/// <b>기본값(0)은 <see cref="Normal"/> 이다.</b> 부하 소스를 조립하지 않은 경로는 압박이
/// 없는 것으로 보고 아무것도 버리지 않는다 — 관측·제어 축을 켜지 않은 조립이 기능을 잃지
/// 않아야 한다는 규약과 같다. (헬스·수용 판정의 "가장 제한적 기본값" 과 방향이 반대인 것은
/// 의도적이다: 여기서 제한적인 기본값은 <b>정상 상태에서 트래픽을 버리는 것</b>이라 더 나쁘다.)
/// </para>
/// <para>
/// <b>단계를 셋으로 두는 이유.</b> 이진(정상/과부하)이면 "조금 밀릴 때 텔레메트리만 끊기"와
/// "심각할 때 필수만 남기기"를 구분할 수 없다. 반대로 단계가 많으면 운영자가 임계를 조율할 수
/// 없다 — 셋이 그 사이의 실용적 타협이다.
/// </para>
/// </remarks>
public enum LoadLevel : byte
{
    /// <summary>여유 있다. 아무것도 버리지 않는다.</summary>
    Normal = 0,

    /// <summary>압박이 시작됐다. 비필수 기능을 먼저 끊는다.</summary>
    Elevated = 1,

    /// <summary>한계다. 필수 기능만 남긴다.</summary>
    Critical = 2,
}
