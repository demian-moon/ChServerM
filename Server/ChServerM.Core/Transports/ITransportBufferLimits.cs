namespace ChServerM.Transports;

/// <summary>
/// 전송이 커넥션당 버퍼링할 수 있는 최대 바이트를 알린다.
/// </summary>
/// <remarks>
/// <para>
/// <b>존재 이유 — 조용한 교착을 시작 시점 예외로 바꾸기 위해서다.</b>
/// </para>
/// <para>
/// 프레임 디코더는 <b>완전한 프레임이 도착하기 전에는 아무것도 소비할 수 없다.</b>
/// 부분 프레임을 소비하면 경계를 잃기 때문이다. 그런데 전송의 수신 버퍼는 소비되지
/// 않은 바이트가 임계값에 닿으면 쓰기를 멈춘다(백프레셔).
/// </para>
/// <para>
/// 두 성질이 만나면 이렇게 된다.
/// </para>
/// <code>
///   프레임 크기 &gt; 전송 버퍼 임계값
///     → 프레임이 다 오기 전에 버퍼가 참
///     → 쓰기 정지, 그런데 디코더는 소비할 수 없음
///     → 영구 교착
/// </code>
/// <para>
/// 증상이 최악이다. 작은 프레임은 멀쩡히 오가다가 <b>큰 메시지 하나에서만</b> 멈추고,
/// 예외도 로그도 없다. 커넥션이 그냥 응답하지 않는다.
/// </para>
/// <para>
/// 전송은 프레이밍을 알지 못하고 프레이밍은 전송을 알지 못한다 — 그래서 이 제약은
/// <b>둘을 조립하는 쪽</b>에서만 검사할 수 있다. 이 인터페이스가 그 검사를 가능하게 한다.
/// </para>
/// <para>
/// 구현하지 않아도 된다. 그때는 빌더가 검사를 건너뛴다 — 버퍼 개념이 없는 전송
/// (메시지 단위 전송, 공유 메모리 등)까지 강제할 이유는 없다.
/// </para>
/// <para>
/// <b>한 프레임이 임계값을 넘어야 한다면</b> 임계값을 올리거나
/// (커넥션 수를 곱한 메모리를 계산해볼 것) 조각화를 쓴다
/// (<see cref="Framing.FrameFlags.Fragmented"/>).
/// </para>
/// </remarks>
public interface ITransportBufferLimits
{
    /// <summary>커넥션 하나가 방향당 버퍼링할 수 있는 최대 바이트.</summary>
    /// <remarks>
    /// 조립하는 쪽은 <c>헤더 크기 + 최대 페이로드 크기</c>가 이 값 이하인지 확인한다.
    /// </remarks>
    long MaxBufferedBytesPerConnection { get; }
}
